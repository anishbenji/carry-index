import { createHash } from "node:crypto";

/**
 * The build-time Content Security Policy (spike PR 8, `docs/spike/static-csp.md` on its branch): every inline
 * `<script>` and `<style>` of the built pages is hashed, and the policy allows inline code by those hashes only, so
 * it never needs `'unsafe-inline'`. Pages carry only code shared by every page (today the one inline stylesheet),
 * so one hash set covers the whole site and `_headers` needs one rule.
 */

const byCodeUnit = (a: string, b: string): number => (a < b ? -1 : a > b ? 1 : 0);

const sha256 = (text: string): string => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;

export interface HashSet {
  scripts: string[];
  styles: string[];
}

/** Every inline `<script>` and `<style>` body in a page, as CSP sources, deduplicated and sorted. */
export function inlineHashes(html: string): HashSet {
  const bodies = (tag: string) =>
    [...html.matchAll(new RegExp(`<${tag}(?![^>]*\\bsrc=)[^>]*>([\\s\\S]*?)</${tag}>`, "g"))].map((m) => m[1] ?? "");
  const unique = (values: string[]) => [...new Set(values)].sort(byCodeUnit);
  return { scripts: unique(bodies("script").map(sha256)), styles: unique(bodies("style").map(sha256)) };
}

const sources = (hashes: readonly string[]): string => (hashes.length === 0 ? "'none'" : hashes.join(" "));

/**
 * The policy: nothing by default; scripts and styles only by hash; images from the site itself (the favicon); no
 * `<base>`, no form posts, no framing.
 */
export function cspPolicy(hashes: Readonly<HashSet>): string {
  return [
    "default-src 'none'",
    `script-src ${sources(hashes.scripts)}`,
    `style-src ${sources(hashes.styles)}`,
    "img-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
    "frame-ancestors 'none'",
  ].join("; ");
}

/**
 * `_headers` with its one `Content-Security-Policy:` line replaced by `policy`. Comments are dropped (they describe
 * the source file) and one line says the file is generated. Throws unless the source has exactly one CSP line.
 */
export function withCsp(headers: string, policy: string): string {
  const lines = headers.split("\n").filter((line) => !line.startsWith("#"));
  const at = lines.flatMap((line, index) => (line.startsWith("  Content-Security-Policy:") ? [index] : []));
  if (at.length !== 1 || at[0] === undefined) {
    throw new Error(`_headers must have exactly one Content-Security-Policy line, found ${at.length}`);
  }
  lines[at[0]] = `  Content-Security-Policy: ${policy}`;
  return [
    "# Generated by the apps/web build from apps/web/public/_headers, with the pages' CSP hashes.",
    ...lines,
  ].join("\n");
}
