import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import { cspPolicy, inlineHashes, withCsp } from "../build/csp.ts";

const hash = (text: string) => `'sha256-${createHash("sha256").update(text, "utf8").digest("base64")}'`;

describe("inlineHashes", () => {
  it("hashes every inline script and style body, deduplicated and sorted, and skips scripts with src", () => {
    const html =
      "<!DOCTYPE html><html><head><style>b{}</style><style>a{}</style><style>a{}</style>" +
      '<script src="/assets/x-12345678.js"></script><script type="module">go()</script></head></html>';
    expect(inlineHashes(html)).toEqual({
      scripts: [hash("go()")],
      styles: [hash("a{}"), hash("b{}")].sort((x, y) => (x < y ? -1 : x > y ? 1 : 0)),
    });
  });

  it("hashes inline code whatever the tag's case, and an attribute that only ends in src (N7)", () => {
    const html = '<SCRIPT>a()</SCRIPT><script data-src="x">b()</script><Style>c{}</Style><script SRC="/s.js"></script>';
    expect(inlineHashes(html)).toEqual({
      scripts: [hash("a()"), hash("b()")].sort((x, y) => (x < y ? -1 : x > y ? 1 : 0)),
      styles: [hash("c{}")],
    });
  });

  it("finds nothing in a page with no inline code", () => {
    expect(inlineHashes("<!DOCTYPE html><p>text</p>")).toEqual({ scripts: [], styles: [] });
  });
});

describe("cspPolicy", () => {
  it("denies everything by default and allows inline code only by hash", () => {
    const policy = cspPolicy({ scripts: [], styles: ["'sha256-abc='"] });
    expect(policy).toBe(
      "default-src 'none'; script-src 'none'; style-src 'sha256-abc='; img-src 'self'; base-uri 'none'; " +
        "form-action 'none'; frame-ancestors 'none'",
    );
    expect(policy).not.toMatch(/unsafe|\*|https?:/);
  });

  it("lists script hashes when a page has inline scripts", () => {
    expect(cspPolicy({ scripts: ["'sha256-s='"], styles: [] })).toContain("script-src 'sha256-s='; style-src 'none'");
  });
});

describe("withCsp", () => {
  const headers = "# a comment\n/*\n  Content-Security-Policy: default-src 'none'\n  X-Content-Type-Options: nosniff\n";

  it("replaces the one CSP line, drops comments and says the file is generated", () => {
    expect(withCsp(headers, "default-src 'none'; style-src 'sha256-x='")).toBe(
      "# Generated by the apps/web build from apps/web/public/_headers, with the pages' CSP hashes.\n" +
        "/*\n  Content-Security-Policy: default-src 'none'; style-src 'sha256-x='\n  X-Content-Type-Options: nosniff\n",
    );
  });

  it("throws unless there is exactly one CSP line", () => {
    expect(() => withCsp("/*\n  X-Content-Type-Options: nosniff\n", "x")).toThrow(/exactly one/);
    expect(() => withCsp("/*\n  Content-Security-Policy: a\n/assets/*\n  Content-Security-Policy: b\n", "x")).toThrow(
      /exactly one/,
    );
  });
});
