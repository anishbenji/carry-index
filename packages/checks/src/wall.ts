import { execFileSync } from "node:child_process";
import type { Dirent } from "node:fs";
import { lstatSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

export interface WallCheck {
  id: string;
  description: string;
  status: "pending" | "implemented";
  /** A pending check: where it will be implemented. */
  milestone?: string;
  /** An implemented check: the deploy-gate command that runs it. */
  command?: string;
}

/**
 * The three privacy-wall checks, built in packages/deploy (privacy-wall design v2, ADR-0049). The gate's `check`
 * runs the schema walk, the seal and the bundle scans (canary, email and local-path heuristics, `_headers`). The
 * import ban runs with the tests, and the build-graph check runs in `deploy` and `triggers`, as does the bindings
 * check, after everything `check` runs. This guard lists them and fails on a tracked Wrangler config.
 */
export const WALL_CHECKS: readonly WallCheck[] = [
  {
    id: "schema-never-public",
    description: "no never-public schema field reaches the public build",
    status: "implemented",
    command: "node packages/deploy/src/bin.ts check <siteDir>",
  },
  {
    id: "canary-export",
    description: "a canary record in the private store never appears in what is deployed",
    status: "implemented",
    command: "node packages/deploy/src/bin.ts check <siteDir>",
  },
  {
    id: "public-worker-bindings",
    description: "the public Worker is deployed with no D1 or R2 binding",
    status: "implemented",
    command: "node packages/deploy/src/bin.ts deploy <siteDir>",
  },
];

/**
 * Any file Wrangler or its experimental config could load as a Worker config: a JSON, JSONC or TOML file whose
 * name starts `wrangler` (wrangler.jsonc, wrangler-preview.json, ...), any `cloudflare.config.*`, and the Vite
 * plugin's `.wrangler/deploy/config.json` redirect.
 */
const WRANGLER_CONFIG =
  /(^|\/)(wrangler[^/]*\.(json|jsonc|toml)|cloudflare\.config\.[^/]+|\.wrangler\/deploy\/config\.json)$/i;

export interface WallResult {
  ok: boolean;
  lines: string[];
}

/**
 * Lists the wall checks and fails if any file git does not ignore is a Wrangler config: in the v2 design every Worker config
 * is generated from code at deploy time, so the repo tracks none.
 */
export function evaluateWall(tracked: readonly string[], checks: readonly WallCheck[] = WALL_CHECKS): WallResult {
  const lines = checks.map((c) =>
    c.status === "pending" ? `${c.id}: pending: ${c.milestone ?? ""}` : `${c.id}: implemented: ${c.command ?? ""}`,
  );
  const configs = tracked.filter((file) => WRANGLER_CONFIG.test(file));
  lines.push(`files checked (tracked or untracked, not ignored): ${tracked.length}`);
  for (const file of configs) {
    lines.push(`FAIL ${file}: Worker configs are generated by packages/deploy; do not add a Wrangler config`);
  }
  return { ok: configs.length === 0, lines };
}

/**
 * The files in the checkout that git does not ignore: tracked files plus untracked ones not covered by a
 * .gitignore (`git ls-files --cached --others --exclude-standard`), as repo-relative paths.
 */
export function repoFiles(root: string): string[] {
  return execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
    cwd: root,
    encoding: "utf8",
  })
    .split("\0")
    .filter((file) => file.length > 0);
}

/** The names Wrangler looks for when no --config is given. */
const DEFAULT_CONFIG_NAMES = ["wrangler.json", "wrangler.jsonc", "wrangler.toml"] as const;

/**
 * Wrangler's default config names that exist at the repo root or at a workspace root (each folder matched by a
 * `<dir>/*` entry in the root package.json's `workspaces`), whether git ignores them or not: Wrangler reads them
 * regardless. Existence only; no file is read.
 */
export function defaultConfigsOnDisk(root: string): string[] {
  const found: string[] = [];
  for (const dir of ["", ...workspaceDirs(root)]) {
    for (const name of DEFAULT_CONFIG_NAMES) {
      const rel = dir === "" ? name : `${dir}/${name}`;
      try {
        lstatSync(join(root, rel));
        found.push(rel);
      } catch {
        // absent
      }
    }
  }
  return found.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

function workspaceDirs(root: string): string[] {
  const pkg: unknown = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const raw = typeof pkg === "object" && pkg !== null ? (pkg as { workspaces?: unknown }).workspaces : undefined;
  const patterns = Array.isArray(raw) ? raw.filter((p): p is string => typeof p === "string") : [];
  const dirs: string[] = [];
  for (const pattern of patterns) {
    if (!pattern.endsWith("/*")) {
      dirs.push(pattern);
      continue;
    }
    const parent = pattern.slice(0, -2);
    let entries: Dirent[];
    try {
      entries = readdirSync(join(root, parent), { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) if (entry.isDirectory()) dirs.push(`${parent}/${entry.name}`);
  }
  return dirs;
}
